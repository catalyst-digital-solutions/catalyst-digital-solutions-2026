// Regenerates src/content/myers/source.generated.ts from the signature-ready
// copy agreement-v1.4-final.md (built from the authoritative agreement-v1.4.md
// by scripts/make-myers-final.mjs). Run both after replacing the source:
//   node scripts/make-myers-final.mjs && node scripts/gen-myers-source.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "src/content/myers");
const out = path.join(dir, "source.generated.ts");
const sha = (s) => createHash("sha256").update(s).digest("hex");
const source = readFileSync(path.join(dir, "agreement-v1.4.md"), "utf8");
const md = readFileSync(path.join(dir, "agreement-v1.4-final.md"), "utf8");
writeFileSync(
  out,
  `// GENERATED by scripts/gen-myers-source.mjs. Do not edit by hand.\n` +
    `// Rendered: src/content/myers/agreement-v1.4-final.md (sha256 ${sha(md)})\n` +
    `// Built from: src/content/myers/agreement-v1.4.md (sha256 ${sha(source)})\n` +
    `export const MYERS_SOURCE_SHA256 = ${JSON.stringify(sha(source))};\n` +
    `export const MYERS_AGREEMENT_SHA256 = ${JSON.stringify(sha(md))};\n` +
    `export const MYERS_AGREEMENT_MARKDOWN = ${JSON.stringify(md)};\n`,
);
console.log("wrote", path.relative(root, out), "final", sha(md), "source", sha(source));
