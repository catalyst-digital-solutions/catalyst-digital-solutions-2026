// Regenerates src/content/myers/source.generated.ts from the authoritative
// v1.4 agreement markdown. Run after replacing agreement-v1.4.md:
//   node scripts/gen-myers-source.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const src = path.join(root, "src/content/myers/agreement-v1.4.md");
const out = path.join(root, "src/content/myers/source.generated.ts");
const md = readFileSync(src, "utf8");
const sha = createHash("sha256").update(md).digest("hex");
writeFileSync(
  out,
  `// GENERATED by scripts/gen-myers-source.mjs. Do not edit by hand.\n` +
    `// Source: src/content/myers/agreement-v1.4.md (sha256 ${sha})\n` +
    `export const MYERS_AGREEMENT_SHA256 = ${JSON.stringify(sha)};\n` +
    `export const MYERS_AGREEMENT_MARKDOWN = ${JSON.stringify(md)};\n`,
);
console.log("wrote", path.relative(root, out), sha);
